// Helper: Get module by ID
export function getCurriculumModule(id: number): CurriculumModule | undefined {
  return ALL_CURRICULUM_MODULES.find((m) => m.id === id);
}

// Helper: Get adjacent modules for Prev/Next navigation
export function getAdjacentCurriculumModules(currentId: number): {
  prev: CurriculumModule | null;
  next: CurriculumModule | null;
  index: number;
  total: number;
} {
  const index = ALL_CURRICULUM_MODULES.findIndex((m) => m.id === currentId);
  if (index === -1) {
    return { prev: null, next: null, index: 0, total: ALL_CURRICULUM_MODULES.length };
  }
  const prev = index > 0 ? ALL_CURRICULUM_MODULES[index - 1] : null;
  const next = index < ALL_CURRICULUM_MODULES.length - 1 ? ALL_CURRICULUM_MODULES[index + 1] : null;
  return {
    prev,
    next,
    index: index + 1,
    total: ALL_CURRICULUM_MODULES.length,
  };
}

// Helper: Search modules across all divisions
export function searchCurriculumModules(
  query: string,
  divisionFilter?: DivisionId | 'all'
): CurriculumModule[] {
  const cleanQ = query.trim().toLowerCase();
  let list = ALL_CURRICULUM_MODULES;
  if (divisionFilter && divisionFilter !== 'all') {
    list = list.filter((m) => m.divisionId === divisionFilter);
  }
  if (!cleanQ) return list;

  return list.filter((m) => {
    if (m.title.toLowerCase().includes(cleanQ)) return true;
    if (m.desc.toLowerCase().includes(cleanQ)) return true;
    if (m.divisionName.toLowerCase().includes(cleanQ)) return true;
    if (m.subCategoryLabel.toLowerCase().includes(cleanQ)) return true;
    if (m.keywords.some((k) => k.toLowerCase().includes(cleanQ))) return true;
    return false;
  });
}
